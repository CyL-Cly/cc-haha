func (m *MainPrint) nativeProcessSkillPrompt(ctx context.Context, scope *cooperative.Scope, name, args string, history []queryloop.Message, uuid json.RawMessage) (*sessioncontroller.ProcessedInput, error) {
	if scope == nil || !scope.BelongsTo(m.Owner) || m.Registry == nil {
		return nil, cooperative.ErrRestricted
	}
	if m.options.Arguments.DisableSlashCommands {
		return m.nativeDisabledSlashInput(scope, name, args, uuid)
	}
	for _, command := range m.Registry.NativePromptDefinitions() {
		metadata := command.Metadata()
		found := metadata.String("name") == name || metadata.Get("userFacingName") != nil && metadata.String("userFacingName") == name
		var aliases []string
		_ = json.Unmarshal(metadata.Get("aliases"), &aliases)
		for _, alias := range aliases {
			found = found || alias == name
		}
		if !found {
			continue
		}
		if string(metadata.Get("userInvocable")) == "false" {
			start := m.options.Native.NowMillis()
			first := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain("/" + name)}))
			second := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain("This skill can only be invoked by Claude, not directly by users. Ask Claude to use the \"" + name + "\" skill for you.")}))
			// Source allocates the caveat after these two user messages, then
			// places it first in processSlashCommand's returned array.
			caveat := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"), "isMeta": json.RawMessage("true")}))
			return &sessioncontroller.ProcessedInput{Messages: []protocol.JSONObject{caveat, first, second}, NoQuery: true, StartMillis: start}, nil
		}
		if e := m.recordNativeSkillUsage(scope, name); e != nil {
			return nil, e
		}
		processed, err := m.nativeSkillPrompt(ctx, scope, command, args, history, uuid)
		var malformed *skillcommands.MalformedCommandError
		if errors.As(err, &malformed) {
			// Source allocates the usage input before the outer local caveat.
			user := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain(malformed.Message)}))
			caveat := m.factory.CreateLocalCaveat()
			return &sessioncontroller.ProcessedInput{Messages: []protocol.JSONObject{caveat, user}, NoQuery: true, StartMillis: m.options.Native.NowMillis()}, nil
		}
		return processed, err
	}
	return nil, mainCap("unknown actual prompt command " + name)
}

// This is the common getMessagesForPromptSlashCommand producer. The Skill
// wrapper filters its loading user; the slash input consumer retains it.
func (m *MainPrint) nativeSkillPrompt(ctx context.Context, scope *cooperative.Scope, command skillcommands.Definition, args string, history []queryloop.Message, uuid json.RawMessage) (*sessioncontroller.ProcessedInput, error) {
	meta := command.Metadata()
	if meta.String("context") == "fork" {
		run, err := m.nativeRunForkedSkill(ctx, scope, command, args)
		if err != nil {
			return m.nativeForkSkillSlashFailure(command, args, err)
		}
		name := command.UserFacingName()
		if name == "" {
			name = command.Name()
		}
		input := "/" + name
		if args != "" {
			input += " " + args
		}
		input = protocol.TrimJavaScriptString(input)
		first := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain(input)}))
		text := nativeForkSkillResultText(run.Messages, "Command completed")
		second := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": quoteMain("<local-command-stdout>\n" + text + "\n</local-command-stdout>")}))
		return &sessioncontroller.ProcessedInput{Messages: []protocol.JSONObject{first, second}, NoQuery: true, NoQueryResultText: text, AttachmentsHandled: true, StartMillis: m.options.Native.NowMillis()}, nil
	}
	inv, e := m.nativeSkillInvocation(scope)
	if e != nil {
		return nil, e
	}
	blocks, e := command.PromptBlocks(ctx, &args, inv)
	if e != nil {
		return nil, e
	}
	text := skillcommands.PromptText(blocks)
	if e = m.nativeSkillHooks(scope, meta); e != nil {
		return nil, e
	}
	nameJSON := meta.Get("name")
	pathJSON := nameJSON
	if source := meta.String("source"); source != "" {
		pathJSON, e = protocol.JoinJavaScriptValuesJSON([]json.RawMessage{quoteMain(source + ":"), nameJSON}, "")
		if e != nil {
			return nil, e
		}
	}
	if e = m.Controller.InvokeSkillJSON(scope, nameJSON, pathJSON, text, m.options.AgentID); e != nil {
		return nil, e
	}
	allowed, e := skillcommands.ParseInvocationTools(meta.Get("allowedTools"))
	if e != nil {
		return nil, e
	}
	mentioned, e := m.nativeSkillMentions(ctx, scope, text)
	if e != nil {
		return nil, e
	}
	attached, e := m.nativeAttachments(scope, history)
	if e != nil {
		return nil, e
	}
	attached = append(mentioned, attached...)
	loadingPieces := []json.RawMessage{quoteMain("<command-message>"), nameJSON, quoteMain("</command-message>\n<command-name>/"), nameJSON, quoteMain("</command-name>")}
	if string(meta.Get("userInvocable")) == "false" && (meta.String("loadedFrom") == "skills" || meta.String("loadedFrom") == "plugin" || meta.String("loadedFrom") == "mcp") {
		loadingPieces = []json.RawMessage{quoteMain("<command-message>"), nameJSON, quoteMain("</command-message>\n<command-name>"), nameJSON, quoteMain("</command-name>\n<skill-format>true</skill-format>")}
	} else if args != "" {
		loadingPieces = append(loadingPieces, quoteMain("\n<command-args>"+args+"</command-args>"))
	}
	loading, e := protocol.JoinJavaScriptValuesJSON(loadingPieces, "")
	if e != nil {
		return nil, e
	}
	first := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": loading, "uuid": uuid}))
	second := messages.OrderedUser(m.factory.CreateUser(storage.Object{"content": rawMain(blocks), "isMeta": json.RawMessage("true")}))
	result := []protocol.JSONObject{first, second}
	for _, attachment := range attached {
		result = append(result, attachment.Record)
	}
	permissions := protocol.NewJSONObject(protocol.JSONField{Name: "type", Value: quoteMain("command_permissions")}, protocol.JSONField{Name: "allowedTools", Value: rawMain(allowed)}, protocol.JSONField{Name: "model", Value: meta.Get("model")})
	result = append(result, m.factory.CreateAttachment(rawMain(permissions)))
	return &sessioncontroller.ProcessedInput{Messages: result, Model: meta.String("model"), Effort: meta.Get("effort"), CommandRules: allowed, AttachmentsHandled: true}, nil
}

func (m *MainPrint) nativeSkillHooks(scope *cooperative.Scope, meta protocol.JSONObject) error {
	if !scope.BelongsTo(m.Owner) {
		return cooperative.ErrRestricted
	}
	hooks := meta.Get("hooks")
	if !planRawTruthy(hooks) {
		return nil
	}
	policy, e := m.options.Native.ResolvePolicy()
	if e != nil {
		return e
	}
	if policy != nil {
		restricted := string(policy.Get("strictPluginOnlyCustomization")) == "true"
		var surfaces []string
		_ = json.Unmarshal(policy.Get("strictPluginOnlyCustomization"), &surfaces)
		for _, surface := range surfaces {
			restricted = restricted || surface == "hooks"
		}
		trusted := false
		for _, source := range []string{"plugin", "policySettings", "built-in", "builtin", "bundled"} {
			trusted = trusted || meta.String("source") == source
		}
		if restricted && !trusted {
			return nil
		}
	}
	var object protocol.JSONObject
	if e := object.UnmarshalJSON(hooks); e != nil {
		return e
	}
	if m.hook == nil {
		return cooperative.ErrRestricted
	}
	return m.hook.RegisterNativeSkillHooks(scope, m.Controller.SessionID(), object, meta.String("skillRoot"))
}
