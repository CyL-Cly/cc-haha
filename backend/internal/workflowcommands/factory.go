// Package workflowcommands supplies the existing Workflow command source to a
// host's one registry and Harness. It never executes a workflow script.
package workflowcommands

import (
	"encoding/json"
	"regexp"
	"unicode/utf16"

	"github.com/NanmiCoder/cc-haha/backend/internal/cooperative"
	"github.com/NanmiCoder/cc-haha/backend/internal/ownerasync"
	"github.com/NanmiCoder/cc-haha/backend/internal/protocol"
)

type CapabilityError struct{ Boundary string }

func (e *CapabilityError) Error() string { return "Workflow command capability: " + e.Boundary }

// Definition contains original parsed file metadata and the complete script.
// Metadata must be generated by this component's parser, not an oracle result.
type Definition struct{ Object protocol.JSONObject }

type Command struct {
	owner       *cooperative.Owner
	gate        *Gate
	name        string
	description json.RawMessage
	source      string
	definition  protocol.JSONObject
}

var safeName = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_-]*$`)
var commandKeys = []string{"type", "name", "description", "progressMessage", "contentLength", "argNames", "source", "isEnabled", "userFacingName", "getPromptForCommand"}

func NewCommand(scope *cooperative.Scope, gate *Gate, definition Definition) (*Command, error) {
	if gate == nil || !scope.BelongsTo(gate.owner) {
		return nil, cooperative.ErrRestricted
	}
	units, err := protocol.DecodeJavaScriptJSONString(definition.Object.Get("name"))
	if err != nil {
		return nil, &CapabilityError{"non-string original name"}
	}
	name := stringUTF16ASCII(units)
	if !safeName.MatchString(name) {
		return nil, &CapabilityError{"name outside validated metadata domain"}
	}
	if _, err = protocol.DecodeJavaScriptJSONString(definition.Object.Get("description")); err != nil {
		return nil, &CapabilityError{"non-string original description"}
	}
	source := "userSettings"
	var originalSource string
	_ = json.Unmarshal(definition.Object.Get("source"), &originalSource)
	switch originalSource {
	case "built-in":
		source = "builtin"
	case "plugin":
		source = "plugin"
	case "projectSettings":
		source = "projectSettings"
	}
	return &Command{owner: gate.owner, gate: gate, name: name, description: append(json.RawMessage(nil), definition.Object.Get("description")...), source: source, definition: definition.Object}, nil
}
func stringUTF16ASCII(units []uint16) string {
	out := make([]byte, len(units))
	for i, c := range units {
		if c > 127 {
			return ""
		}
		out[i] = byte(c)
	}
	return string(out)
}
func quote(s string) json.RawMessage { return protocol.QuoteJavaScriptUTF16(utf16.Encode([]rune(s))) }
func (c *Command) check(scope *cooperative.Scope) error {
	if c == nil || !scope.BelongsTo(c.owner) {
		return cooperative.ErrRestricted
	}
	return nil
}
func (c *Command) Keys() []string { return append([]string(nil), commandKeys...) }
func (c *Command) Name() string   { return c.name }
func (c *Command) Descriptor(scope *cooperative.Scope) (protocol.JSONObject, error) {
	if err := c.check(scope); err != nil {
		return protocol.JSONObject{}, err
	}
	description, _ := protocol.DecodeJavaScriptJSONString(c.description)
	return protocol.NewJSONObject(protocol.JSONField{Name: "type", Value: quote("prompt")}, protocol.JSONField{Name: "name", Value: quote(c.name)}, protocol.JSONField{Name: "description", Value: c.description}, protocol.JSONField{Name: "progressMessage", Value: quote("running the " + c.name + " workflow")}, protocol.JSONField{Name: "contentLength", Value: json.RawMessage(itoa(len(description) + 200))}, protocol.JSONField{Name: "argNames", Value: []byte(`["args"]`)}, protocol.JSONField{Name: "source", Value: quote(c.source)}), nil
}
func itoa(value int) string { raw, _ := json.Marshal(value); return string(raw) }
func (c *Command) IsEnabled(scope *cooperative.Scope) (bool, error) {
	if err := c.check(scope); err != nil {
		return false, err
	}
	reason, err := c.gate.DisabledReason(scope)
	return reason == "", err
}
func (c *Command) UserFacingName(scope *cooperative.Scope) (string, error) {
	if err := c.check(scope); err != nil {
		return "", err
	}
	units, e := protocol.DecodeJavaScriptJSONString(c.definition.Get("name"))
	if e != nil {
		return "", &CapabilityError{"late name outside original string domain"}
	}
	name := stringUTF16ASCII(units)
	if len(units) > 0 && name == "" {
		return "", &CapabilityError{"late name outside original validated ASCII domain"}
	}
	return name, nil
}

// BeginPrompt preserves the original async factory's fulfilled Promise and its
// real caller reaction; no physical worker observes mutable command data.
func (c *Command) BeginPrompt(scope *cooperative.Scope, args json.RawMessage) (*ownerasync.OwnerFuture[json.RawMessage], error) {
	if err := c.check(scope); err != nil {
		return nil, err
	}
	units, err := protocol.DecodeJavaScriptJSONString(args)
	if err != nil {
		return nil, &CapabilityError{"prompt arguments must be original string"}
	}
	units = trimUnits(units)
	argsLine := "Pass no `args`."
	if len(units) > 0 {
		argsLine = "Convert the following invocation text into the `args` value and pass it: " + string(protocol.QuoteJavaScriptUTF16(units)) + ". If it is a list of items, pass a real JSON array, not a string."
	}
	liveName, e := c.UserFacingName(scope)
	if e != nil {
		return nil, e
	}
	text := `Run the saved workflow "` + liveName + `" by calling Workflow exactly once with { name: "` + liveName + `" }. ` + argsLine + "\n" + "Do not write a new script and do not do the work yourself — the saved workflow already contains the orchestration. After the tool returns, end your turn; the result arrives as a task notification."
	// argsLine contains JSON-escaped lone units, matching the Source string text.
	block := protocol.NewJSONObject(protocol.JSONField{Name: "type", Value: quote("text")}, protocol.JSONField{Name: "text", Value: quote(text)})
	raw, e := block.MarshalJSON()
	if e != nil {
		return nil, e
	}
	future, e := ownerasync.NewOwnerFuture[json.RawMessage](c.owner)
	if e != nil {
		return nil, e
	}
	if e = future.Resolve(scope, append(append([]byte{'['}, raw...), ']')); e != nil {
		return nil, e
	}
	return future, nil
}
func trimUnits(units []uint16) []uint16 {
	for len(units) > 0 && jsWhitespace(units[0]) {
		units = units[1:]
	}
	for len(units) > 0 && jsWhitespace(units[len(units)-1]) {
		units = units[:len(units)-1]
	}
	return units
}
func jsWhitespace(c uint16) bool {
	return c == 9 || c == 10 || c == 11 || c == 12 || c == 13 || c == 32 || c == 0xa0 || c == 0x1680 || c >= 0x2000 && c <= 0x200a || c == 0x2028 || c == 0x2029 || c == 0x202f || c == 0x205f || c == 0x3000 || c == 0xfeff
}
