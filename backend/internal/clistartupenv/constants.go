func keySet(recipe string) map[string]bool {
	result := map[string]bool{}
	for _, key := range strings.Fields(recipe) {
		result[key] = true
	}
	return result
}

// IsProviderManagedEnvVar shares the actual Source inference-routing predicate
// with native desktop launchers such as the scheduled-task dispatcher.
func IsProviderManagedEnvVar(key string) bool { return providerManagedKey(key) }

func providerManagedKey(key string) bool {
	upper := strings.ToUpper(key)
	return providerKeys[upper] || strings.HasPrefix(upper, "VERTEX_REGION_CLAUDE_")
}
